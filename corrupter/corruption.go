package corrupter

import "math/rand"

// NOTE: See https://en.wikipedia.org/wiki/Combining_character

var (
	// above are the runes that are rendered above text.
	above = []rune{
		0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0305, 0x0306, 0x0307, 0x0308, 0x0309,
		0x030A, 0x030B, 0x030C, 0x030D, 0x030E, 0x030F, 0x0310, 0x0311, 0x0312, 0x0313,
		0x0314, 0x0315, 0x031A, 0x031B, 0x033D, 0x033E, 0x033F, 0x0340, 0x0341, 0x0342,
		0x0343, 0x0344, 0x0346, 0x034A, 0x034B, 0x034C, 0x035D, 0x035E, 0x0360, 0x0361,
	}
	// below are the runes that are rendered below text.
	below = []rune{
		0x0316, 0x0317, 0x0318, 0x0319, 0x031C, 0x031D, 0x031E, 0x031F, 0x0320, 0x0321,
		0x0322, 0x0323, 0x0324, 0x0325, 0x0326, 0x0327, 0x0328, 0x0329, 0x032A, 0x032B,
		0x032C, 0x032D, 0x032D, 0x032E, 0x032F, 0x0330, 0x0331, 0x0332, 0x0333, 0x0339,
		0x033A, 0x033B, 0x033C, 0x034D, 0x034E, 0x0353, 0x0354, 0x0355, 0x0356, 0x0359,
		0x035A, 0x035C, 0x035F, 0x0362,
	}
	// within are the runes rendered inside text.
	within = []rune{
		0x0335, 0x0336, 0x0337, 0x0338,
	}
	corruption []rune
)

// selectRune selects randomly from a slice.
func selectRune(slice []rune) rune {
	index := rand.Intn(len(slice))
	return slice[index]
}

// selectCorruption randomly selects one of the corruption runes.
func selectCorruption() rune {
	return selectRune(corruption)
}

func init() {
	corruption = make([]rune, 0, len(above)+len(below)+len(within))
	corruption = append(corruption, above...)
	corruption = append(corruption, below...)
	corruption = append(corruption, within...)
}
